export const RTL_LANGUAGES: LanguageCode[] = ['ur', 'ar'];

export function isRtlLanguage(lang: LanguageCode): boolean {
  return RTL_LANGUAGES.includes(lang);
}

export type SupportedLanguage = LanguageCode;

export interface LanguageConfig {
  code: LanguageCode;
  name: string;
  nativeName: string;
  dir: 'ltr' | 'rtl';
  fontFamily: string;
}

export function getLanguageConfig(lang: LanguageCode): LanguageConfig {
  const isRtl = isRtlLanguage(lang);
  let font = "'Source Serif 4', Georgia, serif";
  if (lang === 'ar') font = "'Amiri', 'Noto Sans Arabic', serif";
  if (lang === 'ur') font = "'Noto Nastaliq Urdu', 'Amiri', serif";
  if (['hi', 'mr'].includes(lang)) font = "'Noto Sans Devanagari', sans-serif";
  return {
    code: lang,
    name: LANGUAGES.find(l => l.code === lang)?.name || 'English',
    nativeName: LANGUAGES.find(l => l.code === lang)?.nativeName || 'English',
    dir: isRtl ? 'rtl' : 'ltr',
    fontFamily: font
  };
}

